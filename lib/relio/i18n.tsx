export type DictKey = keyof (typeof dict)["th"]

type LangContextValue = {
  lang: Lang
  setLang: (lang: Lang) => void
  t: (key: DictKey) => string
  money: (value: number) => string
  date: (iso: string, withTime?: boolean) => string
}

const LangContext = React.createContext<LangContextValue | null>(null)

const STORAGE_KEY = "relio-lang"

export function LangProvider({ children }: { children: React.ReactNode }) {
  const [lang, setLangState] = React.useState<Lang>("th")

  React.useEffect(() => {
    try {
      const saved = window.localStorage.getItem(STORAGE_KEY)
      if (saved === "th" || saved === "en") setLangState(saved)
    } catch {}
  }, [])

  React.useEffect(() => {
    document.documentElement.lang = lang
  }, [lang])

  const value = React.useMemo<LangContextValue>(() => {
    const locale = lang === "th" ? "th-TH" : "en-GB"
    const moneyFmt = new Intl.NumberFormat(locale, {
      style: "currency",
      currency: "THB",
      maximumFractionDigits: 0,
    })
    return {
      lang,
      setLang: (next) => {
        setLangState(next)
        try {
          window.localStorage.setItem(STORAGE_KEY, next)
        } catch {}
      },
      t: (key) => dict[lang][key],
      money: (v) => moneyFmt.format(v),
      date: (iso, withTime = false) =>
        new Intl.DateTimeFormat(locale, {
          day: "numeric",
          month: "short",
          year: "numeric",
          ...(withTime ? { hour: "2-digit", minute: "2-digit" } : {}),
        }).format(new Date(iso)),
    }
  }, [lang])

  return <LangContext.Provider value={value}>{children}</LangContext.Provider>
}

export function useLang() {
  const ctx = React.useContext(LangContext)
  if (!ctx) throw new Error("useLang must be used inside LangProvider")
  return ctx
}
